class SwitchExample {
public static void main(String[] args) {
final int i = 0;
final int j = 2;
final int f = 30;
switch (0) {
case i:
System.out.println("Five");
break;
case j:
System.out.println("Ten");
break;
case f:
System.out.println("Seven");
break;
default:
System.out.println("Default");
break;
  }
 }
}